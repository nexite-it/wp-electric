<?php
/**
 * Template: generic archive fallback.
 *
 * Used for any post type archive, taxonomy, author or date archive that has
 * no dedicated template (template-<type>.php). Renders the main query so
 * pagination keeps working.
 */

defined('ABSPATH') || exit;

use SiteKit\Util;



\SiteKit\Template\partial('header', []);
?>
<main id="content">
    <?php
    Util\page_hero([
        'eyebrow' => __('Archiv', 'site-kit'),
        'title'   => wp_strip_all_tags(get_the_archive_title()),
        'lead'    => wp_strip_all_tags((string) get_the_archive_description()),
        'crumbs'  => [['label' => wp_strip_all_tags(get_the_archive_title())]],
    ]);
    ?>

    <section class="sk-section">
        <div class="sk-wrap">
            <?php if (have_posts()) : ?>
                <div class="sk-grid sk-grid--3">
                    <?php
                    $index = 0;
                    while (have_posts()) :
                        the_post();
                        \SiteKit\Template\partial('news-card', ['post' => get_post(), 'delay' => $index % 3]);
                        $index++;
                    endwhile;
                    ?>
                </div>

                <?php echo Util\pagination(); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by core ?>
            <?php else : ?>
                <div class="sk-empty reveal">
                    <div class="sk-empty__icon"><?php Util\icon('doc', ''); ?></div>
                    <h2><?php esc_html_e('Noch nichts veröffentlicht', 'site-kit'); ?></h2>
                    <p><?php esc_html_e('Sobald hier etwas veröffentlicht wird, erscheint es an dieser Stelle.', 'site-kit'); ?></p>
                </div>
            <?php endif; ?>
        </div>
    </section>
</main>
<?php
\SiteKit\Template\partial('footer');
