<?php
/**
 * Template: news archive.
 *
 * Doubles as the blog index and as the archive for the `news` post type. Uses
 * the main query so pagination works without a custom WP_Query.
 */

defined('ABSPATH') || exit;

use SiteKit\Content;
use SiteKit\Util;

$intro   = Content\page_intro('news');
$is_blog = is_home();

\SiteKit\Template\partial('header', ['page_key' => 'news']);
?>
<main id="content">
    <?php
    Util\page_hero([
        'eyebrow' => $intro['eyebrow'],
        'title'   => $is_blog ? __('Blog', 'site-kit') : $intro['title'],
        'lead'    => $intro['lead'],
        'crumbs'  => $is_blog ? [] : [['label' => $intro['title']]],
    ]);
    ?>

    <section class="sk-section">
        <div class="sk-wrap">
            <?php if (have_posts()) : ?>
                <div class="sk-grid sk-grid--3">
                    <?php
                    $index = 0;
                    while (have_posts()) :
                        the_post();
                        \SiteKit\Template\partial('news-card', ['post' => get_post(), 'delay' => $index % 3]);
                        $index++;
                    endwhile;
                    ?>
                </div>

                <?php echo Util\pagination(); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by core ?>
            <?php else : ?>
                <div class="sk-empty reveal">
                    <div class="sk-empty__icon"><?php Util\icon('megaphone', ''); ?></div>
                    <h2><?php esc_html_e('Nothing published yet', 'site-kit'); ?></h2>
                    <p><?php esc_html_e('New posts appear here automatically.', 'site-kit'); ?></p>
                </div>
            <?php endif; ?>
        </div>
    </section>
</main>
<?php
\SiteKit\Template\partial('footer');
