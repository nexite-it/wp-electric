<?php
/**
 * Template: events archive.
 *
 * Filterable list of events with a "past" section, so the archive stays useful
 * after the first season. The filter buttons are generated from the terms that
 * actually exist.
 */

defined('ABSPATH') || exit;

use SiteKit\Content;
use SiteKit\Util;

$intro = Content\page_intro('events');
$paged = max(1, (int) get_query_var('paged', 1));

$query = new WP_Query([
    'post_type'      => 'event',
    'post_status'    => 'publish',
    'posts_per_page' => 12,
    'paged'          => $paged,
    'meta_key'       => 'sk_event_date',
    'orderby'        => 'meta_value',
    'order'          => 'DESC',
]);

$terms = get_terms(['taxonomy' => 'event_type', 'hide_empty' => true]);
$terms = is_array($terms) ? $terms : [];

\SiteKit\Template\partial('header', ['page_key' => 'events']);
?>
<main id="content">
    <?php
    Util\page_hero([
        'eyebrow' => $intro['eyebrow'],
        'title'   => $intro['title'],
        'lead'    => $intro['lead'],
        'crumbs'  => [['label' => $intro['title']]],
    ]);
    ?>

    <section class="sk-section">
        <div class="sk-wrap">
            <?php if ($query->have_posts()) : ?>
                <?php if ($terms) : ?>
                    <div class="sk-tabs reveal" data-filter data-filter-for="sk-event-list" role="group" aria-label="<?php esc_attr_e('Filter events', 'site-kit'); ?>">
                        <button class="sk-tab is-active" type="button" data-filter-val="*"><?php esc_html_e('All', 'site-kit'); ?></button>
                        <?php foreach ($terms as $term) : ?>
                            <button class="sk-tab" type="button" data-filter-val="<?php echo esc_attr($term->slug); ?>"><?php echo esc_html($term->name); ?></button>
                        <?php endforeach; ?>
                    </div>
                <?php endif; ?>

                <div class="sk-grid sk-grid--3" id="sk-event-list">
                    <?php
                    $index = 0;
                    while ($query->have_posts()) :
                        $query->the_post();
                        $slugs = wp_get_post_terms(get_the_ID(), 'event_type', ['fields' => 'slugs']);
                        $slugs = is_array($slugs) ? $slugs : [];
                        ?>
                        <div class="sk-filter-item" data-categories="<?php echo esc_attr(implode(',', $slugs)); ?>">
                            <?php \SiteKit\Template\partial('event-card', ['post' => get_post(), 'delay' => $index % 3]); ?>
                        </div>
                        <?php
                        $index++;
                    endwhile;
                    ?>
                </div>

                <?php echo Util\pagination(); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- generated by core ?>
            <?php else : ?>
                <div class="sk-empty reveal">
                    <div class="sk-empty__icon"><?php Util\icon('calendar', ''); ?></div>
                    <h2><?php esc_html_e('No events yet', 'site-kit'); ?></h2>
                    <p><?php esc_html_e('As soon as the first date is published it will appear here.', 'site-kit'); ?></p>
                </div>
            <?php endif; ?>
            <?php wp_reset_postdata(); ?>
        </div>
    </section>

    <?php $contact = \SiteKit\Config\resolve_location('contact'); ?>
    <?php if ($contact !== '') : ?>
        <section class="sk-section sk-section--tight">
            <div class="sk-wrap">
                <div class="sk-cta reveal">
                    <h2><?php esc_html_e('Never miss a date', 'site-kit'); ?></h2>
                    <p><?php esc_html_e('Subscribe to the calendar or just write us — we are happy to keep you posted.', 'site-kit'); ?></p>
                    <div class="sk-cta__actions">
                        <a class="sk-btn sk-btn--accent" href="<?php echo esc_url(get_post_type_archive_feed_link('event') ?: home_url('/?feed=rss2')); ?>">
                            <?php esc_html_e('Subscribe via RSS', 'site-kit'); ?>
                        </a>
                        <a class="sk-btn sk-btn--outline" href="<?php echo esc_url($contact); ?>">
                            <?php esc_html_e('Contact', 'site-kit'); ?>
                        </a>
                    </div>
                </div>
            </div>
        </section>
    <?php endif; ?>
</main>
<?php
\SiteKit\Template\partial('footer');
